/**
 * A deck: one slide per state of the scene's state container, in declaration order (a tree in
 * depth-first order). Without a container on the scene, the outermost container in the tree is used.
 */
class Deck(
    val owner: String?,
    val slides: List<String>,
    val scenes: List<ResolvedScene>,
    val containers: List<ContainerInfo>,
    private val pr: ProcessResult? = null,
    private val options: ResolveOptions = ResolveOptions(),
) {
    companion object {
        fun build(pr: ProcessResult, options: ResolveOptions, collect: (List<diagrams.model.Diagnostic>) -> Unit): Deck? {
            val probe = Resolver.resolve(pr, options)
            collect(probe.diagnostics)
            val base = probe.scene ?: return null
            val c = probe.containers.firstOrNull { it.owner == "scene" } ?: probe.containers.minByOrNull { it.depth }
                ?: return Deck(null, listOf("-"), listOf(base), emptyList())
            val ids = order(c.container)
            val scenes = ids.map { id ->
                val r = Resolver.resolve(pr, options.copy(states = options.states + (c.owner to id)))
                collect(r.diagnostics)
                r.scene ?: return null
            }
            return Deck(c.owner, ids, scenes, probe.containers, pr, options)
        }

        private fun order(c: StateContainer): List<String> = c.states.map { it.id }
    }

    /** The frames of the transition from slide [i] to slide [i + 1], at [fps], ends excluded. */
    fun frames(i: Int, fps: Double): List<ResolvedScene> {
        val p = pr ?: return emptyList()
        val t = Resolver.transition(p, scenes[i].states, scenes[i + 1].states, options).transition ?: return emptyList()
        val n = (t.duration * fps).toInt()
        return (1 until n).map { k -> t.frame(k / fps) }
    }
}

/** Writes a deck as a self-contained HTML page, a PDF, or a folder of SVG or PNG slides. */
object DeckWriter {
    fun html(deck: Deck, title: String, manifest: AssetManifest, fontFiles: Map<String, File>, background: String?, fps: Double, withMedia: (SvgRenderer.Options) -> SvgRenderer.Options = { it }): String {
        val fonts = fontFiles.mapValues { (name, _) -> SvgRenderer.Font("", manifest.font(name)!!) }
        val opts = withMedia(SvgRenderer.Options(background = background, fonts = fonts, fontFaces = false))
        // consecutive frames share most of their SVG lines: each distinct line is stored once, and a
        // slide or frame is the list of its line numbers
        val table = LinkedHashMap<String, Int>()
        fun svg(s: ResolvedScene): String = SvgRenderer.render(s, opts.copy(background = background ?: s.background ?: "#ffffff"))
            .trimEnd('\n').split('\n').joinToString(",", "[", "]") { line -> table.getOrPut(line) { table.size }.toString() }
        val slides = deck.scenes.joinToString(",\n") { svg(it) }
        val frames = (0 until deck.scenes.size - 1).joinToString(",\n") { i -> deck.frames(i, fps).joinToString(",", "[", "]") { svg(it) } }
        val lines = table.keys.joinToString(",\n") { JsonWriter.string(it) }
        val css = fontFiles.entries.joinToString("\n") { (name, f) ->
            SvgRenderer.fontFaceCss(name, "data:font/ttf;base64," + java.util.Base64.getEncoder().encodeToString(f.readBytes()))
        }
        val names = JsonWriter.string(deck.slides.joinToString("|"))
        return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
$css
html, body { margin: 0; height: 100%; background: #1e1e1e; overflow: hidden; font-family: sans-serif; }
#stage { position: fixed; inset: 0; display: flex; align-items: center; justify-content: center; cursor: pointer; }
#stage svg { width: 100vw; height: 100vh; display: block; }
#bar { position: fixed; right: 12px; bottom: 8px; color: #888; font-size: 12px; user-select: none; }
</style>
</head>
<body>
<div id="stage"></div>
<div id="bar"></div>
<script>
// Generated by diagrams deck. Keys: right / space / page down: next; left / page up: back; home, end; f: full screen.
const lines = [
$lines
];
const svg = ix => ix.map(i => lines[i]).join("\n");
const slides = [
$slides
];
const frames = [
$frames
];
const names = $names.split("|");
const fps = $fps;
const stage = document.getElementById("stage"), bar = document.getElementById("bar");
let current = 0, playing = null;
function show(ix) { stage.innerHTML = svg(ix); }
function settle(i) {
  current = i; show(slides[i]);
  bar.textContent = (i + 1) + " / " + slides.length + "  " + names[i];
  history.replaceState(null, "", "#" + (i + 1));
}
function play(list, done) {
  if (playing) { clearInterval(playing); playing = null; }
  let k = 0;
  if (!list.length) return done();
  playing = setInterval(() => {
    if (k >= list.length) { clearInterval(playing); playing = null; done(); return; }
    show(list[k++]);
  }, 1000 / fps);
}
function go(i, animate) {
  if (i < 0 || i >= slides.length || i === current) return;
  if (animate && Math.abs(i - current) === 1) {
    const list = i > current ? frames[current] : frames[i].slice().reverse();
    play(list, () => settle(i));
  } else settle(i);
}
document.addEventListener("keydown", e => {
  if (["ArrowRight", " ", "PageDown", "Enter"].includes(e.key)) { go(current + 1, true); e.preventDefault(); }
  else if (["ArrowLeft", "PageUp", "Backspace"].includes(e.key)) { go(current - 1, true); e.preventDefault(); }
  else if (e.key === "Home") go(0, false);
  else if (e.key === "End") go(slides.length - 1, false);
  else if (e.key === "f") { document.fullscreenElement ? document.exitFullscreen() : document.documentElement.requestFullscreen(); }
});
stage.addEventListener("click", e => go(current + (e.clientX < window.innerWidth / 3 ? -1 : 1), true));
const start = parseInt(location.hash.slice(1), 10);
settle(start >= 1 && start <= slides.length ? start - 1 : 0);
</script>
</body>
</html>
"""
    }

    private fun esc(s: String) = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    /** One page per slide, each an image rendered at [scale]: the deck looks the same in any PDF reader. */
    fun pdf(deck: Deck, out: File, options: RasterRenderer.Options) {
        val objects = mutableListOf<ByteArray>()
        fun add(b: ByteArray): Int {
            objects += b
            return objects.size
        }
        val w = deck.scenes.first().width
        val h = deck.scenes.first().height
        val catalog = add(ByteArray(0))
        val pages = add(ByteArray(0))
        val pageIds = mutableListOf<Int>()
        for (scene in deck.scenes) {
            val img = RasterRenderer.render(scene, options.copy(background = options.background ?: scene.background ?: "#ffffff"))
            val rgb = ByteArray(img.width * img.height * 3)
            var i = 0
            for (y in 0 until img.height) for (x in 0 until img.width) {
                val p = img.getRGB(x, y)
                rgb[i++] = (p shr 16).toByte()
                rgb[i++] = (p shr 8).toByte()
                rgb[i++] = p.toByte()
            }
            val data = deflate(rgb)
            val image = add(stream("<< /Type /XObject /Subtype /Image /Width ${img.width} /Height ${img.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /FlateDecode /Length ${data.size} >>", data))
            val content = "q ${num(w)} 0 0 ${num(h)} 0 0 cm /Im Do Q".toByteArray()
            val contents = add(stream("<< /Length ${content.size} >>", content))
            pageIds += add("<< /Type /Page /Parent $pages 0 R /MediaBox [0 0 ${num(w)} ${num(h)}] /Resources << /XObject << /Im $image 0 R >> >> /Contents $contents 0 R >>".toByteArray())
        }
        objects[catalog - 1] = "<< /Type /Catalog /Pages $pages 0 R >>".toByteArray()
        objects[pages - 1] = "<< /Type /Pages /Kids [${pageIds.joinToString(" ") { "$it 0 R" }}] /Count ${pageIds.size} >>".toByteArray()
        val buf = ByteArrayOutputStream()
        buf.write("%PDF-1.4\n%âãÏÓ\n".toByteArray(Charsets.ISO_8859_1))
        val offsets = mutableListOf<Int>()
        objects.forEachIndexed { k, o ->
            offsets += buf.size()
            buf.write("${k + 1} 0 obj\n".toByteArray())
            buf.write(o)
            buf.write("\nendobj\n".toByteArray())
        }
        val xref = buf.size()
        buf.write("xref\n0 ${objects.size + 1}\n0000000000 65535 f \n".toByteArray())
        for (o in offsets) buf.write("%010d 00000 n \n".format(o).toByteArray())
        buf.write("trailer\n<< /Size ${objects.size + 1} /Root $catalog 0 R >>\nstartxref\n$xref\n%%EOF\n".toByteArray())
        out.writeBytes(buf.toByteArray())
    }

    private fun num(d: Double) = diagrams.model.formatNumber(d)

    private fun stream(dict: String, data: ByteArray): ByteArray {
        val b = ByteArrayOutputStream()
        b.write("$dict\nstream\n".toByteArray())
        b.write(data)
        b.write("\nendstream".toByteArray())
        return b.toByteArray()
    }

    private fun deflate(data: ByteArray): ByteArray {
        val d = Deflater(Deflater.BEST_COMPRESSION)
        d.setInput(data)
        d.finish()
        val out = ByteArrayOutputStream()
        val chunk = ByteArray(1 shl 16)
        while (!d.finished()) out.write(chunk, 0, d.deflate(chunk))
        d.end()
        return out.toByteArray()
    }

    /** One file per slide: `01-<state>.svg` or `.png`. */
    fun folder(deck: Deck, dir: File, format: String, svg: SvgRenderer.Options, png: RasterRenderer.Options) {
        dir.mkdirs()
        deck.scenes.forEachIndexed { i, s ->
            val name = "%02d-%s".format(i + 1, deck.slides[i])
            if (format == "svg") {
                File(dir, "$name.svg").writeText(SvgRenderer.render(s, svg.copy(background = svg.background ?: s.background ?: "#ffffff")))
            } else {
                ImageIO.write(RasterRenderer.render(s, png.copy(background = png.background ?: s.background ?: "#ffffff")), "png", File(dir, "$name.png"))
            }
        }
    }
}
